"""Pydantic data models exchanged between the RAG stages."""
import uuid
from typing import List

from pydantic import BaseModel, Field


class MinimalSource(BaseModel):
    """A source location inside a file.

    Attributes:
        file_path: Path of the file the chunk comes from.
        first_character_index: Offset of the first character.
        last_character_index: Offset just past the last character.
        content: Raw text of the chunk.
    """

    file_path: str
    first_character_index: int
    last_character_index: int
    content: str


class UnansweredQuestion(BaseModel):
    """A question without ground truth.

    Attributes:
        question_id: Unique identifier, generated when missing.
        question: Text of the question.
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """A question with its reference sources and answer.

    Attributes:
        sources: Ground-truth sources supporting the answer.
        answer: Reference answer text.
    """

    sources: List[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """A dataset of RAG questions.

    Attributes:
        rag_questions: Questions, answered or not.
    """

    rag_questions: List[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """Retrieved sources for one question.

    Attributes:
        question_id: Identifier of the originating question.
        question: Text of the question.
        retrieved_sources: Sources returned by the retrieval stage.
    """

    question_id: str
    question: str
    retrieved_sources: List[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Retrieved sources plus the generated answer.

    Attributes:
        answer: Answer generated by the model.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Output of search_dataset.

    Attributes:
        search_results: Per-question retrieval results.
        k: Number of sources requested per question.
    """

    search_results: List[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Output of answer_dataset.

    Attributes:
        search_results: Per-question results with answers.
        k: Number of sources requested per question.
    """

    search_results: List[MinimalAnswer]
    k: int
