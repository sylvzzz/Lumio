import { useRef, useEffect } from 'react'
import { motion, AnimatePresence, useReducedMotion } from 'framer-motion'
import { Bot, Send, Plus, X } from 'lucide-react'
import { useChatComposer } from '@/hooks/use-chat-composer'
import { useAIPanelStore } from '@/store/ai-panel'
import { Markdown } from '@/components/Markdown'
import { SourceRows } from '@/components/SourceRows'
import { sourceFiles } from '@/lib/sources'
import { TypingDots } from '@/components/TypingDots'
import { useUser } from '@/hooks/useUser'

function getText(lang: string) {
  const pt = {
    'ask_anything': 'Pergunte-me qualquer coisa sobre suas notas, documentos, emails ou calendário.',
    'ask_lumio': 'Pergunte ao Lumio qualquer coisa.',
    'generated_by': 'Gerado por Lumio',
  }
  const en = {
    'ask_anything': 'Ask me anything about your notes, documents, emails, or calendar.',
    'ask_lumio': 'Ask Lumio anything.',
    'generated_by': 'Generated by Lumio',
  }
  return lang === 'pt' ? pt : en
}

export function AIPanel() {
  const { user } = useUser()
  const shouldReduceMotion = useReducedMotion()
  const width = useAIPanelStore((s) => s.width)
  const setWidth = useAIPanelStore((s) => s.setWidth)
  const closePanel = useAIPanelStore((s) => s.closePanel)
  const { input, setInput, sending, messages, isLoading, currentSession, handleSend, handleNewChat } = useChatComposer()
  const messagesEndRef = useRef<HTMLDivElement>(null)
  const scrollRef = useRef<HTMLDivElement>(null)
  const autoScrollRef = useRef(true)

  useEffect(() => {
    if (!autoScrollRef.current) return
    messagesEndRef.current?.scrollIntoView({
      behavior: shouldReduceMotion ? 'auto' : 'smooth',
      block: 'end',
    })
  }, [messages, sending, shouldReduceMotion])

  const handleScroll = () => {
    const el = scrollRef.current
    if (!el) return
    autoScrollRef.current = el.scrollHeight - el.scrollTop - el.clientHeight < 120
  }

  const startResize = (e: React.PointerEvent) => {
    e.preventDefault()
    const startX = e.clientX
    const startWidth = width
    const onMove = (ev: PointerEvent) => {
      setWidth(startWidth + (startX - ev.clientX))
    }
    const onUp = () => {
      document.body.style.cursor = ''
      window.removeEventListener('pointermove', onMove)
      window.removeEventListener('pointerup', onUp)
    }
    document.body.style.cursor = 'col-resize'
    window.addEventListener('pointermove', onMove)
    window.addEventListener('pointerup', onUp)
  }

  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault()
      handleSend()
    }
  }

  const i18n = getText(user.language ?? 'pt')

  return (
    <div className="flex-1 flex flex-col min-h-0">
      <div
        onPointerDown={startResize}
        role="separator"
        aria-orientation="vertical"
        className="hidden lg:block absolute -left-1.5 top-0 bottom-0 w-3 cursor-col-resize z-20 group/rs"
      >
        <div className="absolute inset-y-0 left-1/2 -translate-x-1/2 w-[3px] rounded-full bg-transparent transition-colors group-hover/rs:bg-accent/30 group-active/rs:bg-accent/60" />
      </div>

      <motion.div
        className="px-4 pt-4 pb-3 lg:px-6 lg:pt-7 lg:pb-4 border-b border-border/50 flex items-center justify-between"
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        transition={{ duration: 0.4 }}
      >
        <div className="flex items-center gap-2.5">
          <div className="w-7 h-7 rounded-lg bg-accent flex items-center justify-center">
            <Bot className="w-4 h-4 text-white" strokeWidth={1.5} />
          </div>
          <div>
            <span className="text-sm font-semibold tracking-tight">Lumio</span>
            <p className="text-[11px] text-muted-foreground leading-none mt-0.5">Your personal AI assistant</p>
          </div>
        </div>
        <div className="flex items-center gap-1.5">
          <motion.button
            onClick={handleNewChat}
            className="h-11 w-11 lg:h-6 lg:w-6 rounded-lg bg-secondary flex items-center justify-center hover:bg-secondary/80 transition-colors shrink-0"
            whileHover={{ scale: 1.05 }}
            whileTap={{ scale: 0.97 }}
            title="New chat"
            aria-label="New chat"
          >
            <Plus className="w-3.5 h-3.5 text-muted-foreground" strokeWidth={1.5} />
          </motion.button>
          <motion.button
            onClick={closePanel}
            className="h-11 w-11 lg:h-6 lg:w-6 rounded-lg bg-secondary flex items-center justify-center hover:bg-destructive/10 hover:text-destructive transition-colors shrink-0"
            whileHover={{ scale: 1.05 }}
            whileTap={{ scale: 0.97 }}
            title="Close panel"
            aria-label="Close chat"
          >
            <X className="w-3.5 h-3.5" strokeWidth={1.5} />
          </motion.button>
        </div>
      </motion.div>

      <div ref={scrollRef} onScroll={handleScroll} className="flex-1 min-h-0 overflow-y-auto overscroll-contain px-4 py-4 lg:px-5 lg:py-5 space-y-4">
        {!currentSession && !isLoading && messages.length === 0 && (
          <div className="flex flex-col items-center justify-center h-full text-center px-4">
            <Bot className="w-8 h-8 text-accent/30 mb-3" strokeWidth={1} />
            <p>{i18n['ask_anything']}</p>
          </div>
        )}

        <AnimatePresence mode="popLayout">
          {messages.map((msg) => {
            const files = msg.role === 'assistant' ? sourceFiles(msg) : []
            return (
            <motion.div
              key={msg.id}
              initial={{ opacity: 0, y: 10, scale: 0.97 }}
              animate={{ opacity: 1, y: 0, scale: 1 }}
              transition={{
                type: 'spring',
                stiffness: 200,
                damping: 20,
                mass: 0.8,
              }}
              className={`flex ${msg.role === 'user' ? 'justify-end' : 'justify-start'}`}
            >
              <div
                className={`max-w-[85%] rounded-2xl px-4 py-3 text-[13px] leading-relaxed ${
                  msg.role === 'user'
                    ? 'bg-secondary text-foreground rounded-br-md'
                    : 'bg-card border border-border/50 text-foreground rounded-bl-md shadow-sm'
                }`}
              >
                {msg.role === 'assistant' && files.length > 0 && (
                  <SourceRows files={files} animate={!!msg.streaming} />
                )}
                {msg.role === 'assistant' && msg.streaming && !msg.content ? (
                  <TypingDots reduceMotion={!!shouldReduceMotion} />
                ) : (
                  <Markdown streaming={!!msg.streaming}>{msg.content}</Markdown>
                )}
              </div>
            </motion.div>
            )
          })}
        </AnimatePresence>

        {sending && !messages.some((m) => m.streaming) && (
          <motion.div
            className="flex justify-start"
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0 }}
          >
            <div className="bg-card border border-border/50 rounded-2xl rounded-bl-md px-4 py-3 shadow-sm">
              <TypingDots reduceMotion={!!shouldReduceMotion} />
            </div>
          </motion.div>
        )}
        <div ref={messagesEndRef} />
      </div>

      <div className="px-4 py-3 lg:px-5 lg:py-4 border-t border-border/50 shrink-0">
        <div className="flex items-center gap-2 bg-card border border-border/50 rounded-2xl px-4 py-2.5 transition-colors">
          <input
            type="text"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={handleKeyDown}
            placeholder={i18n['ask_lumio']}
            disabled={sending}
            className="flex-1 min-w-0 text-[13px] bg-transparent placeholder:text-muted-foreground/50 focus:outline-none disabled:opacity-50"
          />
          <motion.button
            onClick={() => handleSend()}
            disabled={sending || !input.trim()}
            aria-label="Send message"
            className="h-11 w-11 lg:h-7 lg:w-7 rounded-lg bg-accent flex items-center justify-center shrink-0 disabled:opacity-40"
            whileHover={{ scale: 1.05 }}
            whileTap={{ scale: 0.97 }}
          >
            <Send className="w-3.5 h-3.5 text-white" strokeWidth={1.5} />
          </motion.button>
        </div>
      </div>
    </div>
  )
}
